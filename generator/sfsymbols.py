"""Generates the `SFSymbol.<name>` constants from the SF Symbols catalog of the installed macOS.

usage: python3 -I generator/sfsymbols.py [project-dir]
"""

import os
import plistlib
import sys

sys.path.insert(0, os.path.dirname(__file__))
from bridges import KOTLIN_KEYWORDS  # noqa: E402

PLIST = "/System/Library/CoreServices/CoreGlyphs.bundle/Contents/Resources/name_availability.plist"
PKG = "dev.nucleusframework.composeswiftui"
PLATFORMS = ("iOS", "macOS", "tvOS", "watchOS", "visionOS")
# Script/locale variants (`character.book.closed.ja`, `arrow.uturn.left.rtl`): SwiftUI picks them from the
# base name and the environment locale, so only the base name gets a constant.
LOCALE_SUFFIXES = {"ar", "hi", "rtl", "he", "zh", "th", "ja", "ko", "sat", "mni", "ml", "kn", "bn", "gu", "or",
                   "mr", "te", "pa", "ta", "si", "el", "ru", "my", "km"}


def kotlin_name(symbol):
    parts = symbol.split(".")
    name = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    if name[0].isdigit():
        name = "_" + name
    return "`%s`" % name if name in KOTLIN_KEYWORDS else name


def main(project):
    with open(PLIST, "rb") as f:
        catalog = plistlib.load(f)
    symbols, releases = catalog["symbols"], catalog["year_to_release"]
    names = sorted(n for n in symbols
                   if not ("." in n and n.rsplit(".", 1)[1] in LOCALE_SUFFIXES and n.rsplit(".", 1)[0] in symbols))
    seen = {}
    lines = [
        "// GENERATED by generator/sfsymbols.py from the SF Symbols catalog. Do not edit.",
        "@file:Suppress(\"unused\", \"ObjectPropertyName\")",
        "",
        "@file:OptIn(kotlin.experimental.ExperimentalObjCRefinement::class)",
        "",
        "package %s" % PKG,
        "",
        "import kotlin.native.HiddenFromObjC",
        "",
    ]
    for n in names:
        kn = kotlin_name(n)
        if kn in seen:
            raise SystemExit("name clash: %s and %s -> %s" % (seen[kn], n, kn))
        seen[kn] = n
        rel = releases[symbols[n]]
        avail = ", ".join("%s %s+" % (p, rel[p]) for p in PLATFORMS if p in rel)
        lines.append("/** `%s` · %s */" % (n, avail))
        lines.append("@HiddenFromObjC public inline val SFSymbol.Companion.%s: SFSymbol get() = SFSymbol(\"%s\")" % (kn, n))
    out = os.path.join(project, "runtime", "src", "generated", "kotlin", *PKG.split("."), "GenSFSymbols.kt")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("%d symbols -> %s" % (len(names), out))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
