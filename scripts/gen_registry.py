#!/usr/bin/env python3
"""Regenerates the Kotlin and Swift screen registries from the screens present in the tree."""
import glob, os, re, sys

root = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else ".")
kt_dir = os.path.join(root, "bench/shared/src/commonMain/kotlin/bench/screens")
sw_dir = os.path.join(root, "bench/app/Screens")
nums = sorted(int(re.search(r"Screen(\d+)\.kt$", f).group(1)) for f in glob.glob(os.path.join(kt_dir, "Screen*.kt")))
nums = [n for n in nums if os.path.exists(os.path.join(sw_dir, "Screen%02dView.swift" % n))]
with open(os.path.join(root, "bench/shared/src/commonMain/kotlin/bench/Registry.kt"), "w") as f:
    f.write("package bench\n\nimport bench.screens.*\n\n// GENERATED by scripts/gen_registry.py — order defines the shared screen index.\n")
    f.write("internal val benchScreens: List<BenchScreen> = listOf(\n")
    for n in nums:
        f.write("    screen%02d,\n" % n)
    f.write(")\n")
with open(os.path.join(root, "bench/app/SwiftRegistry.swift"), "w") as f:
    f.write("import SwiftUI\n\n// GENERATED by scripts/gen_registry.py — pure SwiftUI screens, indexed like BenchRegistry.\n")
    f.write("@MainActor\nenum SwiftScreens {\n    static func make(_ index: Int, _ vm: BenchViewModel) -> AnyView {\n        switch index {\n")
    for i, n in enumerate(nums):
        f.write("        case %d: return AnyView(Screen%02dView(vm: vm as! Screen%02dViewModel))\n" % (i, n, n))
    f.write("        default: return AnyView(Text(\"Missing screen \\(index)\"))\n        }\n    }\n\n")
    f.write("    /// Screen number (as in ScreenNN) for each index.\n    static let numbers: [Int] = [%s]\n}\n" % ", ".join(str(n) for n in nums))
print("registered screens:", nums)
