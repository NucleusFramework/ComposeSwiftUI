package dev.nucleusframework.composeswiftui.gradle

import org.gradle.api.DefaultTask
import org.gradle.api.Project
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import org.gradle.api.tasks.TaskProvider
import org.jetbrains.kotlin.gradle.dsl.KotlinMultiplatformExtension
import org.jetbrains.kotlin.gradle.plugin.KotlinCompilation
import org.jetbrains.kotlin.gradle.plugin.mpp.KotlinNativeTarget

/** Dependency groups that bring Compose UI (and its `LocalDensity`) into a module. */
private val COMPOSE_UI_GROUPS = listOf(
    "org.jetbrains.compose.ui", "org.jetbrains.compose.foundation", "org.jetbrains.compose.material",
    "org.jetbrains.compose.components", "androidx.compose.ui", "androidx.compose.foundation", "androidx.compose.material",
)

/** True when a dependency declared in [project] brings Compose UI. */
internal fun declaresComposeUi(project: Project): Boolean =
    project.configurations.any { configuration ->
        configuration.dependencies.any { dependency -> COMPOSE_UI_GROUPS.any { dependency.group?.startsWith(it) == true } }
    }

/**
 * When the module uses Compose UI (directly or through Compose Multiplatform resources), every host must provide
 * Compose UI's `LocalDensity`, which `stringResource` reads: generates a host decorator that provides it from the
 * SwiftUI `displayScale`, registered at startup.
 */
internal fun registerComposeUiDefaults(project: Project, kotlin: KotlinMultiplatformExtension): TaskProvider<GenerateComposeSwiftUIDefaultsTask> =
    project.tasks.register("generateComposeSwiftUIDefaults", GenerateComposeSwiftUIDefaultsTask::class.java) { task ->
        task.group = "compose swiftui"
        task.description = "Generates the Compose UI defaults (LocalDensity) of the module's hosts, when it uses Compose UI."
        task.enabledForComposeUi.set(project.provider { declaresComposeUi(project) })
        task.packageName.set("dev.nucleusframework.composeswiftui.generated." + project.path.trim(':').replace(Regex("[^A-Za-z0-9]+"), "_").ifEmpty { "root" })
        task.targetNames.set(
            project.provider {
                kotlin.targets.withType(KotlinNativeTarget::class.java).filter { it.konanTarget.family.isAppleFamily }.map { it.name }
            },
        )
        task.outputDirectory.set(project.layout.buildDirectory.dir("generated/composeSwiftUI/defaults/kotlin"))
    }.also { defaults ->
        kotlin.targets.withType(KotlinNativeTarget::class.java).configureEach { target ->
            if (target.konanTarget.family.isAppleFamily) {
                target.compilations.named(KotlinCompilation.MAIN_COMPILATION_NAME) { compilation ->
                    compilation.defaultSourceSet.kotlin.srcDir(defaults.flatMap { it.outputDirectory.dir(target.name) })
                }
            }
        }
    }

@CacheableTask
abstract class GenerateComposeSwiftUIDefaultsTask : DefaultTask() {
    @get:Input
    abstract val enabledForComposeUi: Property<Boolean>

    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val targetNames: ListProperty<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val root = outputDirectory.get().asFile
        root.deleteRecursively()
        for (target in targetNames.get()) {
            // One directory per target: Kotlin doesn't let source sets share a directory.
            val dir = root.resolve(target).apply { mkdirs() }
            if (enabledForComposeUi.get()) dir.resolve("ComposeSwiftUIComposeUiDefaults.kt").writeText(source(packageName.get()))
        }
    }

    private fun source(packageName: String) = """
        |// Generated by the Compose SwiftUI Gradle plugin: the module uses Compose UI, so every host provides Compose UI's
        |// LocalDensity (Compose Multiplatform resources read it), from the SwiftUI displayScale.
        |@file:OptIn(kotlin.ExperimentalStdlibApi::class)
        |@file:Suppress("DEPRECATION")
        |
        |package $packageName
        |
        |import androidx.compose.runtime.Composable
        |import androidx.compose.runtime.CompositionLocalProvider
        |import androidx.compose.ui.platform.LocalDensity
        |import androidx.compose.ui.unit.Density
        |import dev.nucleusframework.composeswiftui.ComposeSwiftUI
        |import dev.nucleusframework.composeswiftui.HostDecorator
        |import dev.nucleusframework.composeswiftui.currentSwiftUIEnvironment
        |
        |private object ComposeUiDensityDecorator : HostDecorator {
        |    @Composable
        |    override fun Decorate(content: @Composable () -> Unit) {
        |        val scale = currentSwiftUIEnvironment.displayScale.toFloat()
        |        CompositionLocalProvider(LocalDensity provides Density(scale), content = content)
        |    }
        |}
        |
        |@kotlin.native.EagerInitialization
        |private val registered: Unit = ComposeSwiftUI.addHostDecorator(ComposeUiDensityDecorator)
        |""".trimMargin()
}
