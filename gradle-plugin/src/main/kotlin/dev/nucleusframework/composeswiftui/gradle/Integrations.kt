package dev.nucleusframework.composeswiftui.gradle

import java.io.File

/** Writes `IntegrationsRegistration.swift`: the `register…()` calls of the integrations the build lists. */
internal object IntegrationsRegistration {
    const val FILE = "IntegrationsRegistration.swift"

    private val REGISTER = Regex("""static func (register\w+)\(([^)]*)\)""")

    /** [integrations]: name and Swift source of each listed integration (empty: nothing registered automatically). */
    fun swift(integrations: List<Pair<String, String>>): String = buildString {
        append("import SwiftUI\n\n")
        append("// Generated by the Compose SwiftUI Gradle plugin from composeSwiftUI { integrations }. Do not edit.\n")
        append("extension ComposeIntegrations {\n")
        append("    /// Registers the integrations listed in `composeSwiftUI { integrations }`. Called by `ComposeGenerated.setUp()`.\n")
        append("    @MainActor static func registerConfigured() {\n")
        for ((name, source) in integrations) {
            val calls = REGISTER.findAll(source).map { it.groupValues[1] }.distinct().toList()
            if (calls.isEmpty()) continue
            val guard = fileGuard(source)
            if (guard != null) append("        #if ").append(guard).append('\n')
            calls.forEach { append("        ").append(it).append("()  // ").append(name).append('\n') }
            if (guard != null) append("        #endif\n")
        }
        append("    }\n}\n")
    }

    /** The `#if` condition wrapping a whole integration file (`os(iOS) || os(watchOS)`), if any. */
    internal fun fileGuard(source: String): String? {
        val firstCode = source.lines().map { it.trim() }.firstOrNull { it.isNotEmpty() && !it.startsWith("//") && !it.startsWith("import ") }
        return firstCode?.takeIf { it.startsWith("#if ") }?.removePrefix("#if ")?.trim()
    }
}

/** What the app's Xcode project references, to warn about renderer files it doesn't compile. */
internal object XcodeProjects {
    /**
     * The renderer files in [rendererDir] that a `project.pbxproj` next to it lists nowhere, when that project lists the
     * renderer's files one by one. Empty when the folder is a synchronized folder (Xcode 16), or no project is found.
     */
    fun missingRendererFiles(rendererDir: File): List<String> {
        val project = generateSequence(rendererDir.parentFile) { it.parentFile }.take(3)
            .flatMap { dir -> dir.listFiles().orEmpty().filter { it.extension == "xcodeproj" }.asSequence() }
            .map { it.resolve("project.pbxproj") }
            .firstOrNull { it.isFile } ?: return emptyList()
        val text = project.readText()
        // A synchronized folder references the folder, not its files
        if ("PBXFileSystemSynchronizedRootGroup" in text && rendererDir.name in text) return emptyList()
        val swiftFiles = rendererDir.walkTopDown().filter { it.isFile && it.extension == "swift" }.map { it.name }.toList()
        // Only a project that lists some of them one by one can miss the others
        if (swiftFiles.none { "/* $it */" in text }) return emptyList()
        return swiftFiles.filter { "/* $it */" !in text }.sorted()
    }
}
